def add_decomposition(m: Macros) -> None:
    """Which uncertainty dominates, at the world and inside a country."""
    dec = read_json("out/uncertainty_decomposition.json")
    sources = dig(dec, "sources", source="decomposition")

    def width(name: str, year: str = "2150") -> float:
        return float(dig(sources, name, "world_width_billions", year,
                         source="decomposition"))

    m.add("DecompositionDraws", str(dec["draws"]))
    m.number("WidthFertility", sanity("fertility width", width("fertility"), 5, 10), 2)
    m.number("WidthMortality", width("mortality"), 2)
    m.number("WidthMigration", width("migration"), 2)
    m.number("WidthEverything", width("everything"), 2)
    m.number("WidthMechanism",
             float(dig(dec, "mechanism", "2150", source="decomposition")), 2)
    # Our own post-2100 rule is reported as what it ADDS, not as a total: ten
    # fewer years of source data widens the same calculation by this much.
    m.number("WidthHoldConstant",
             width("stop-at-2090") - width("everything"), 2)
    m.number("WidthFertilityTwentyOneHundred", width("fertility", "2100"), 2)

    countries = {
        name: dig(sources, name, "countries_2100_width_millions",
                  source="decomposition")
        for name in ("fertility", "migration")
    }
    for iso3, label in (("ARE", "Uae"), ("NGA", "Nigeria"), ("CAN", "Canada")):
        ratio = countries["migration"][iso3] / countries["fertility"][iso3]
        m.number(f"MigrationOverFertility{label}", ratio, 2)


def add_comparator(m: Macros) -> None:
    """The conventional mean-reverting baseline, stored before Phase 5 existed."""
    uw = read_json("out/uw_ensemble.json")
    world = dig(uw, "world_billions", source="uw ensemble")
    m.add("ComparatorDraws", str(uw["draws"]))
    m.add("ComparatorCountries", str(uw["locations"]))
    medians = {int(year): float(band["p50"]) for year, band in world.items()}
    peak_year = max(medians, key=medians.get)
    m.add("ComparatorPeakYear", str(peak_year))
    m.number("ComparatorPeak", medians[peak_year], 2)
    final = world[str(max(medians))]
    m.number("ComparatorTwentyOneFifty", float(final["p50"]), 2)
    m.number("ComparatorTwentyOneFiftyLow", float(final["p05"]), 2)
    m.number("ComparatorTwentyOneFiftyHigh", float(final["p95"]), 2)


def add_continuation(m: Macros) -> None:
    """The post-2100 rate continuation, and what the old frozen rule was worth.

    Both runs propagate the same posterior through the same engine and differ
    only after 2100, so the difference between them is exactly the cost of the
    assumption -- which is better than the proxy it replaces, where the source
    data was truncated ten years early to estimate the same thing.
    """
    continued = read_json("out/uw_ensemble_continued.json")
    held = read_json("out/uw_ensemble.json")
    fit = dig(continued, "post_2100_continuation", source="continued ensemble")

    m.number("ContinuationTfrPhi", float(fit["tfr_phi_median"]), 2)
    m.number("ContinuationTfrSigma", float(fit["tfr_sigma_median"]), 3)
    m.number("ContinuationEZeroDrift",
             float(fit["e0_drift_years_per_year_median"]), 3)
    low, high = fit["e0_drift_years_per_year_range"]
    m.number("ContinuationEZeroDriftLow", float(low), 3)
    m.number("ContinuationEZeroDriftHigh", float(high), 3)
    share = float(fit["clipped_share"])
    m.add("ContinuationClippedShare", f"{share:.1e}".replace("e-0", "e$-$"))
    m.add("ContinuationFitStart", str(fit["fit_years"][0]))

    def band(payload: dict) -> tuple[float, float, float]:
        world = dig(payload, "world_billions", source="ensemble")
        final = world[str(max(int(y) for y in world))]
        return float(final["p05"]), float(final["p50"]), float(final["p95"])

    c_low, c_mid, c_high = band(continued)
    h_low, h_mid, h_high = band(held)
    m.number("ContinuedTwentyOneFifty",
             sanity("continued 2150 median", c_mid, 7.0, 13.0), 2)
    m.number("ContinuedLow", c_low, 2)
    m.number("ContinuedHigh", c_high, 2)
    m.number("HoldVsContinueMedian", c_mid - h_mid, 2)
    m.number("HoldVsContinueWidth", (c_high - c_low) - (h_high - h_low), 2)


def add_validation(m: Macros) -> None:
    """The engine test that makes any later difference attributable."""
    report = read_json("out/validation_wpp2024.json")
    checks = dig(report, "checks", source="validation")
    if not report.get("pass"):
        raise ResultError("the engine validation did not pass; do not build a paper on it")

    m.percent("ValidationWorld",
              abs(float(dig(checks, "world_total", "rel_error_2100",
                            source="validation"))), 3)
    m.percent("ValidationCountry",
              abs(float(dig(checks, "countries", "worst_rel_error",
                            source="validation"))), 2)
    m.add("ValidationWorstCountry",
          str(dig(checks, "countries", "worst_iso3", source="validation")))
    m.add("ValidationGatedCountries",
          str(dig(checks, "countries", "n_gated", source="validation")))
    m.percent("ValidationAge",
              abs(float(dig(checks, "age_structure",
                            "worst_closed_group_rel_error", source="validation"))), 3)
    m.percent("ValidationOpenAge",
              abs(float(dig(checks, "age_structure", "open_group_rel_error",
                            source="validation"))), 2)
    m.percent("ValidationMediumDiagnostic",
              abs(float(dig(report, "diagnostic_medium", "world_rel_error",
                            source="validation"))), 2)

    # The absurdity check: freeze fertility and compare against the UN's own
    # constant-fertility variant rather than against a remembered figure.
    long_run = read_json("out/run_to_2150.json")
    constant = dig(long_run, "constant_fertility_check", source="run_to_2150")
    m.percent("ValidationConstantFertility",
              abs(float(constant["rel_error_2100"])), 2)
    m.number("ConstantFertilityTwentyOneFifty",
             float(constant["world_2150_ours"]) / 1e9, 0)


