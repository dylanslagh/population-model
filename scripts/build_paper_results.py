LATEX_ESCAPES = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                 "_": r"\_", "{": r"\{", "}": r"\}"}


def latex_escape(text: str) -> str:
    return "".join(LATEX_ESCAPES.get(character, character) for character in text)


def write_parameter_table() -> None:
    """The mechanism parameter table, typeset straight from the source CSV.

    Typing this table by hand is exactly how a parameter silently stops matching
    the value the model ran with, so it is generated. The `kind` column is the
    one readers should look at: `sourced` rows have evidence, `knob` rows do not
    and cannot, and no amount of literature review converts one into the other.
    """
    path = REPO / "data/reference/mechanism_parameters.csv"
    rows = list(csv.DictReader(path.read_text(encoding="utf-8").splitlines()))
    lines = [
        "% Generated by scripts/build_paper_results.py from",
        "% data/reference/mechanism_parameters.csv. Do not edit by hand.",
        r"\begin{tabular}{@{}llrrl@{}}",
        r"\toprule",
        r"Parameter & Kind & Value & Range & Unit \\",
        r"\midrule",
    ]
    for kind in ("sourced", "knob"):
        for row in rows:
            if row["kind"] != kind:
                continue
            name = latex_escape(row["name"].replace("_", " "))
            value, low, high = (float(row["value"]), float(row["low"]),
                                float(row["high"]))
            places = 0 if value >= 100 or value == int(value) and value >= 3 else (
                5 if value < 0.01 else 3)
            span = "---" if low == high else f"{low:.{places}f}--{high:.{places}f}"
            lines.append(
                f"{name} & {row['kind']} & {value:.{places}f} & {span} & "
                f"{latex_escape(row['unit'])} \\\\"
            )
        if kind == "sourced":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLE.relative_to(REPO)} with {len(rows)} parameters")


