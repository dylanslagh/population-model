"""Regenerate the paper's numerical macros from committed result files.

The paper's rule is that no headline result is typed into prose if a result
file can produce it. This script is the mechanism for that rule: every number
the manuscript quotes comes through a macro defined here, so a rerun of the
model changes the paper rather than leaving it quietly stale.

It fails rather than degrades. A missing file, a missing key, or a value that
has drifted outside a sanity bound stops the build, because a paper that
compiles with a silently wrong number is worse than one that does not compile.

    python scripts/build_paper_results.py
"""

from __future__ import annotations

