class ResultError(RuntimeError):
    """A result file did not contain what the manuscript needs."""


def read_json(relative: str) -> dict:
    path = REPO / relative
    if not path.exists():
        raise ResultError(
            f"{relative} is missing. Regenerate it before building the paper; "
            f"see HANDOFF.md section 6 for the command that writes it."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def dig(payload: dict, *keys, source: str):
    node = payload
    for key in keys:
        if not isinstance(node, dict) or key not in node:
            trail = " -> ".join(str(k) for k in keys)
            raise ResultError(f"{source} has no {trail}")
        node = node[key]
    return node


class Macros:
    """Accumulates LaTeX definitions and refuses to define one twice."""

    def __init__(self) -> None:
        self._items: list[tuple[str, str]] = []
        self._seen: set[str] = set()

    def add(self, name: str, value: str) -> None:
        if name in self._seen:
            raise ResultError(f"macro {name} defined twice")
        if not name.isalpha():
            raise ResultError(f"macro {name} must be letters only for LaTeX")
        self._seen.add(name)
        self._items.append((name, value))

    def number(self, name: str, value: float, places: int, *, unit: str = "") -> None:
        self.add(name, f"{value:.{places}f}{unit}")

    def percent(self, name: str, fraction: float, places: int) -> None:
        self.add(name, f"{100 * fraction:.{places}f}\\%")

    def render(self) -> str:
        width = max(len(name) for name, _ in self._items)
        lines = [
            "% Generated by scripts/build_paper_results.py. Do not edit by hand.",
            "% Every headline number in the manuscript is defined here and comes",
            "% from a result file in out/ or data/reference/.",
            "",
        ]
        lines += [
            f"\\newcommand{{\\{name}}}{{{value}}}".replace(
                f"{{\\{name}}}", f"{{\\{name}}}".ljust(width + 4)
            )
            for name, value in self._items
        ]
        return "\n".join(lines) + "\n"


def sanity(label: str, value: float, low: float, high: float) -> float:
    if not low <= value <= high:
        raise ResultError(
            f"{label} is {value}, outside the expected {low} to {high}. Either "
            f"the model changed materially or a result file is stale; check "
            f"before relaxing this bound."
        )
    return value


def add_mechanism(m: Macros) -> None:
    """The selection mechanism: parameters, the grid, the parameter ensemble."""
    phase5 = read_json("out/phase5.json")
    scenarios = dig(phase5, "scenarios", source="out/phase5.json")

    def world(key: str, year: str) -> float:
        return float(dig(scenarios, key, "world_billions", year, source="phase5"))

    m.number("PhaseFiveBaseYear", float(phase5["base_year"]), 0)
    m.add("ProjectionEndYear", str(phase5["end_year"]))

    # The two-axis grid corners.
    m.number("UnEquivalentTwentyOneFifty", world("un-equivalent", "2150"), 2)
    m.number("UnEquivalentPeak",
             float(scenarios["un-equivalent"]["peak_billions"]), 2)
    m.add("UnEquivalentPeakYear", str(scenarios["un-equivalent"]["peak_year"]))
    m.number("PressureOnlyTwentyOneFifty", world("development-pressure", "2150"), 2)
    m.number("RaceTwentyOneFifty", world("race", "2150"), 2)
    m.number("RacePeak", float(scenarios["race"]["peak_billions"]), 2)
    m.add("RacePeakYear", str(scenarios["race"]["peak_year"]))
    m.number("MainstreamOnlyTwentyOneFifty", world("mainstream-only", "2150"), 2)
    m.number("FullSelectionUnTwentyOneFifty",
             world("full-selection-un-environment", "2150"), 2)
    m.number("AnchoredTwentyOneFifty", world("race-anchored-culture", "2150"), 2)
    m.number("ConvergenceTwentyOneFifty", world("race-with-convergence", "2150"), 2)

    # The selection multiplier: observed fertility over the environment path.
    race_effect = sanity(
        "race selection effect at 2150",
        float(scenarios["race"]["world_selection_effect_final"]), 1.0, 1.6,
    )
    m.number("RaceSelectionEffect", race_effect, 3)
    m.percent("RaceSelectionEffectPercent", race_effect - 1.0, 1)
    anchored_effect = float(
        scenarios["race-anchored-culture"]["world_selection_effect_final"]
    )
    m.number("AnchoredSelectionEffect", anchored_effect, 3)
    m.percent("AnchoredSelectionEffectPercent", anchored_effect - 1.0, 1)
    m.number("MainstreamSelectionEffect",
             float(scenarios["mainstream-only"]["world_selection_effect_final"]), 3)

    # Separability: the same selection setting under two environments that end
    # billions of people apart. The residual gap is the claim's honest size.
    calm = float(scenarios["selection-rebound"]["world_selection_effect_final"])
    stressed = float(scenarios["race"]["world_selection_effect_final"])
    m.number("SeparabilityCalmEffect", calm, 3)
    m.number("SeparabilityStressedEffect", stressed, 3)
    m.percent("SeparabilityGap", abs(calm - stressed) / calm, 2)
    m.number("SeparabilityPopulationGap",
             abs(world("selection-rebound", "2150") - world("race", "2150")), 2)
    m.add("SelectionOvertakesYear",
          str(scenarios["race"]["selection_overtakes_in"]))
    m.add("FinalRateYear", str(scenarios["race"]["final_rate_year"]))

    # World composition at the horizon: who the population is made of.
    composition = scenarios["race"]["world_composition_2150"]
    m.percent("CompositionHighShare", float(composition["mainstream-high"]), 1)
    m.percent("CompositionLowShare", float(composition["mainstream-low"]), 1)
    m.percent("CompositionMiddleShare", float(composition["mainstream-middle"]), 1)
    m.percent("CompositionGroupShare", float(composition["named-group"]), 1)
    m.percent("CompositionStartShare", 1.0 / 3.0, 1)

    # Country heterogeneity in the same run.
    watch = scenarios["race"]["watch_countries"]
    for iso3, label in (("ISR", "Israel"), ("USA", "UnitedStates"),
                        ("NGA", "Nigeria"), ("KOR", "Korea"), ("JPN", "Japan"),
                        ("DEU", "Germany")):
        m.number(f"SelectionEffect{label}",
                 float(watch[iso3]["selection_effect_2150"]), 2)
    m.percent("IsraelGroupShare",
              float(watch["ISR"]["composition_2150"]["named-group"]), 0)
    m.percent("UnitedStatesGroupShare",
              float(watch["USA"]["composition_2150"]["named-group"]), 1)

    # The parameter ensemble: the mechanism's own uncertainty.
    ensemble = dig(phase5, "ensemble", source="out/phase5.json")
    race_band = dig(ensemble, "race", "world_2150_billions", source="ensemble")
    m.add("MechanismDraws", str(ensemble["draws"]))
    m.number("RaceEnsembleLow", float(race_band["p05"]), 2)
    m.number("RaceEnsembleMedian", float(race_band["p50"]), 2)
    m.number("RaceEnsembleHigh", float(race_band["p95"]), 2)
    effect_band = dig(ensemble, "race", "selection_effect_2150", source="ensemble")
    m.number("RaceEnsembleEffectLow", float(effect_band["p05"]), 3)
    m.number("RaceEnsembleEffectHigh", float(effect_band["p95"]), 3)
    m.percent("RaceEnsembleOvertakeShare",
              float(ensemble["race"]["share_where_selection_overtakes"]), 0)

    # Spec 6.6's compounding illustration, run rather than asserted.
    toy = dig(phase5, "toy_demonstration", "shares_by_generation",
              source="out/phase5.json")
    m.percent("ToyFinalShare", float(toy[-1]), 0)
    m.add("ToyGenerations", str(len(toy)))


def add_ladder_and_boundary(m: Macros) -> None:
    """The attribution ladder and the break-even environmental decline."""
    sens = read_json("data/reference/selection_break_even_sensitivity.json")
    ladder = {row["key"]: row for row in dig(sens, "model_ladder", source="ladder")}
    for key, name in (
        ("stable-low-no-selection", "LadderBenchmark"),
        ("selection-only-mainstream", "LadderMainstream"),
        ("selection-only-full", "LadderNamedGroups"),
        ("race-four-percent", "LadderPressure"),
    ):
        m.number(name, float(ladder[key]["world_2150_billions"]), 2)
    m.number("LadderMainstreamGain",
             float(ladder["selection-only-mainstream"]["change_from_previous_billions"]), 2)
    m.number("LadderNamedGroupsGain",
             float(ladder["selection-only-full"]["change_from_previous_billions"]), 2)
    m.number("LadderPressureLoss",
             abs(float(ladder["race-four-percent"]["change_from_previous_billions"])), 2)
    m.add("PressureFromYear", str(sens["pressure_from"]))

    # Two ratios the prose leans on, derived here so they cannot drift from the
    # figures they describe.
    mainstream_gain = float(
        ladder["selection-only-mainstream"]["change_from_previous_billions"])
    group_gain = float(ladder["selection-only-full"]["change_from_previous_billions"])
    m.percent("LadderMainstreamGainPercent",
              mainstream_gain / float(ladder["stable-low-no-selection"]
                                      ["world_2150_billions"]), 0)
    m.percent("NamedGroupShareOfMechanism", group_gain / mainstream_gain, 1)

    rows = {(round(r["mainstream_propensity_cv"], 2),
             round(r["mainstream_persistence"], 3)): r for r in sens["rows"]}
    central = rows[(0.57, 0.15)]
    m.number("MainstreamSelectionMultiplier",
             float(central["selection_effect_final"]), 3)
    m.percent("BoundaryDeterministic",
              sanity("deterministic boundary",
                     float(central["break_even_decline_per_decade"]), 0.005, 0.05), 2)

    corners = [(0.44, 0.05), (0.80, 0.30)]
    for (cv, persistence), name in zip(corners, ("BoundaryFloor", "BoundaryCeiling")):
        m.percent(name, float(rows[(cv, round(persistence, 3))]
                              ["break_even_decline_per_decade"]), 2)

    # Cancelling the terminal rate and cancelling the accumulated population are
    # different questions with different answers, and reporting only the first
    # overstates what the boundary shows.
    population = dig(sens, "population_break_even", source="ladder")
    m.percent("BoundaryPopulation",
              sanity("population boundary",
                     float(population["break_even_decline_per_decade"]), 0.005, 0.08), 2)
    m.number("BoundaryPopulationWorld",
             float(population["world_2150_billions_at_break_even"]), 2)

    paired = read_json("data/reference/paired_selection_boundary_sensitivity.json")
    band = dig(paired, "central_result", "break_even_decline_per_decade",
               source="paired boundary")
    m.percent("BoundaryPaired",
              sanity("paired boundary", float(band["p50"]), 0.005, 0.05), 2)
    m.percent("BoundaryPairedLow", float(band["p05"]), 2)
    m.percent("BoundaryPairedHigh", float(band["p95"]), 2)
    m.add("PairedMigrationPaths", str(dig(paired, "migration", "paths",
                                          source="paired boundary")))
    m.add("BoundaryGridCells", str(len(paired["rows"])))


def add_parameters(m: Macros) -> None:
    """The measured inputs to the mechanism, and how many are not measured."""
    path = REPO / "data/reference/mechanism_parameters.csv"
    rows = list(csv.DictReader(path.read_text(encoding="utf-8").splitlines()))
    if not rows:
        raise ResultError("mechanism_parameters.csv is empty")
    sourced = [r for r in rows if r["kind"] == "sourced"]
    knobs = [r for r in rows if r["kind"] == "knob"]
    if len(sourced) + len(knobs) != len(rows):
        raise ResultError("a mechanism parameter is neither sourced nor a knob")
    m.add("MechanismParameterCount", str(len(rows)))
    m.add("MechanismSourcedCount", str(len(sourced)))
    m.add("MechanismKnobCount", str(len(knobs)))
    if any(r["verified"] != "TRUE" for r in sourced):
        raise ResultError("a sourced mechanism parameter is not marked verified")
    if any(r["verified"] == "TRUE" for r in knobs):
        raise ResultError("a scenario knob claims to be verified")

    values = {r["name"]: r for r in rows}
    cv = values["mainstream_propensity_cv"]
    m.number("FamilySizeCV", float(cv["value"]), 2)
    m.number("FamilySizeCVLow", float(cv["low"]), 2)
    m.number("FamilySizeCVHigh", float(cv["high"]), 2)
    persistence = values["mainstream_persistence"]
    m.number("Persistence", float(persistence["value"]), 2)
    m.number("PersistenceLow", float(persistence["low"]), 2)
    m.number("PersistenceHigh", float(persistence["high"]), 2)
    m.add("MainstreamTypes", str(int(float(values["mainstream_types"]["value"]))))
    m.percent("PressureStressTest",
              float(values["development_decline_per_decade"]["value"]), 0)
    m.number("HarediFertility", float(values["group_fertility_haredi"]["value"]), 2)
    m.percent("HarediRetention", float(values["group_retention_haredi"]["value"]), 1)
    m.percent("HarediShare", float(values["group_share_haredi"]["value"]), 1)
    m.number("AmishFertility", float(values["group_fertility_amish"]["value"]), 2)
    m.percent("AmishRetention", float(values["group_retention_amish"]["value"]), 1)
    m.percent("AmishShare", float(values["group_share_amish"]["value"]), 3)
    m.percent("DefectorWeight",
              float(values["defector_high_propensity_weight"]["value"]), 0)

    # One generation's predicted relative response, persistence times CV squared.
    response = float(persistence["value"]) * float(cv["value"]) ** 2
    m.percent("GenerationResponse", response, 2)

    # What the empirical dispersion range is worth, propagated rather than refit.
    cv_sens = read_json("data/reference/mainstream_propensity_cv_sensitivity.json")
    race_rows = {round(r["cv"], 2): r for r in cv_sens["rows"]
                 if r["scenario"] == "race"}
    m.number("CVLowWorld", float(race_rows[0.44]["world_2150_billions"]), 2)
    m.number("CVHighWorld", float(race_rows[0.80]["world_2150_billions"]), 2)

    cv_json = read_json("data/reference/mainstream_propensity_cv.json")
    low = dig(cv_json, "low_fertility_mean_le_2_2", source="cv receipt")
    m.add("CVCountries", str(low["countries"]))
    m.add("CVAllCountries", str(dig(cv_json, "all_usable", "countries",
                                    source="cv receipt")))
    m.number("CVWomenMillions", float(low["women"]) / 1e6, 1)
    m.number("CVMedian", float(low["unweighted_median"]), 3)
    m.number("CVMin", float(low["unweighted_min"]), 3)
    m.number("CVMax", float(low["unweighted_max"]), 3)
    m.number("CVUnitedStates",
             float(dig(cv_json, "us_cross_check", "cv_geometric",
                       source="cv receipt")), 3)
    m.number("CVUnitedStatesMean",
             float(dig(cv_json, "us_cross_check", "mean_children",
                       source="cv receipt")), 2)


